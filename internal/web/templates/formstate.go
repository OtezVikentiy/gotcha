package templates

// FormState — значения, введённые пользователем, для повторной отрисовки формы
// после ошибки валидации.
//
// Существует потому, что формы в модалках теряли всё: страница при 422
// отрисовывается заново, фрагмента #id в адресе уже нет, модалка закрывается, а
// поля приходят пустыми. Человек заполнял семь полей, ошибался в одном и
// начинал сначала — при том что онбординг ровно эту проблему решает правильно
// (Onboarding принимает введённые значения именно затем, чтобы не терять их).
//
// Хранится плоской картой имя-поля → значение: формы разные, а поведение нужно
// одинаковое, и заводить структуру на каждую форму значило бы плодить типы ради
// одного и того же.
type FormState map[string]string

// Get возвращает введённое значение или fallback, если поля не было.
// nil-приёмник безопасен: на первом открытии формы состояния ещё нет.
func (f FormState) Get(name, fallback string) string {
	if f == nil {
		return fallback
	}
	if v, ok := f[name]; ok {
		return v
	}
	return fallback
}

// formModalKey — служебный ключ: какую модалку открыть с сервера. Живёт в той
// же карте, а не отдельным параметром, потому что путешествует ровно с ней —
// обработчик, который вернул значения формы, всегда знает и форму.
//
// Имя с двумя подчёркиваниями не может совпасть с именем поля: карта собирается
// обработчиком поимённо из известных полей, а не копированием r.Form целиком.
const formModalKey = "__modal"

// Open помечает, какую модалку открыть при повторной отрисовке, и возвращает ту
// же карту — чтобы писать templates.FormState{...}.Open("new-channel") в одну
// строку прямо в вызове рендера.
func (f FormState) Open(id string) FormState {
	if f == nil {
		f = FormState{}
	}
	f[formModalKey] = id
	return f
}

// Opens сообщает, надо ли открыть модалку id с сервера.
//
// Раньше признаком служил сам факт непустого состояния: модалка на странице
// была одна, и «есть значения» означало «открой её». С появлением правки
// каналов, команд и окон обслуживания модалок на странице стало по одной на
// строку таблицы, и ошибка в форме правки открывала бы заодно форму создания.
func (f FormState) Opens(id string) bool { return f[formModalKey] == id }

// Has сообщает, есть ли введённые значения (служебные ключи не считаются).
func (f FormState) Has() bool {
	n := len(f)
	if _, ok := f[formModalKey]; ok {
		n--
	}
	return n > 0
}

// Selected — атрибут selected для <option>, если это значение выбрано.
func (f FormState) Selected(name, value, fallback string) bool {
	return f.Get(name, fallback) == value
}
