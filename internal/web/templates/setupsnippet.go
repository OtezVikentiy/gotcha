package templates

// SetupSnippet — один блок страницы подключения: язык, команда установки пакета
// и код инициализации.
//
// Раньше страница показывала три захардкоженных сниппета с несуществующими
// пакетами (gitflic.ru/otezvikentiy/gotcha-go, @gotcha/browser, Gotcha\init) и
// без единой команды установки. Первый же шаг нового пользователя упирался в 404
// от go get / npm install, притом что собственная документация продукта
// (/docs/sdk) прямо говорит обратное: своего протокола у Gotcha нет, ставится
// официальный Sentry SDK нужного языка, а DSN просто указывает на Gotcha.
type SetupSnippet struct {
	// Lang — заголовок блока («Go», «PHP», «JavaScript (браузер)», «Python»).
	Lang string
	// Install — команда установки пакета. Показывается первой: без неё сниппет
	// инициализации бесполезен.
	Install string
	// Code — минимальная инициализация с подставленным DSN.
	Code string
}
