-- backward-compatible: yes (новая таблица)
--
-- Применённые сроки хранения телеметрии. TTL в ClickHouse — свойство
-- ИНСТАЛЛЯЦИИ, а задавался он окружением КАЖДОЙ реплики: две реплики с разными
-- значениями перекидывали TTL туда-обратно на каждом рестарте, и каждый
-- переброс — это ALTER TABLE MODIFY TTL, то есть пересчёт по всем кускам
-- таблицы. Молча.
--
-- Таблица не отменяет настройку через окружение: она делает расхождение
-- видимым — реплика сравнивает своё значение с применённым и пишет об
-- отличии в лог.
CREATE TABLE retention_state (
    key        text PRIMARY KEY,
    days       int  NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT now()
);
