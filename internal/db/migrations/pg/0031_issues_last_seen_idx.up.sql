-- backward-compatible: yes (новый индекс)
--
-- Находка №5: чистильщик сущностей (internal/telemetry/entity_janitor.go,
-- entityRules) фильтрует issues по last_seen. Ни один существующий индекс
-- issues не начинается с last_seen — issues_project_last_seen_idx начинается
-- с project_id и рассчитан на листинг проблем ОДНОГО проекта, а не на скан
-- всей таблицы по возрасту. Проход чистильщика — раз в час, гарантированный
-- полный скан всей таблицы каждый раз, и первый проход по накопленному
-- объёму квадратичен по числу батчей.
--
-- CONCURRENTLY: обычный CREATE INDEX держит ACCESS EXCLUSIVE на всё время
-- построения — на боевом объёме issues это остановило бы приём событий на
-- ощутимое время. CONCURRENTLY этого не делает ценой того, что не может
-- идти внутри транзакционного блока.
--
-- Один индекс на файл — не стиль, а вывод эксперимента (см. task-1-report.md
-- подпроекта «цена запросов», 2026-08-02): golang-migrate шлёт содержимое
-- файла ОДНИМ вызовом ExecContext на *sql.DB (driver github.com/jackc/pgx/v5
-- /stdlib), а PostgreSQL исполняет simple-query строку с несколькими
-- операторами как ОДНУ неявную транзакцию — CONCURRENTLY внутри неё запрещён
-- (SQLSTATE 25001). Проверено эмпирически на тестовой базе: файл с ОДНИМ
-- CREATE INDEX CONCURRENTLY проходит, файл с ДВУМЯ — падает. x-multi-
-- statement в проекте не включён (см. MigrateCH в migrate.go), поэтому
-- вывод общий для всех migrations/pg, не только для этого файла.
--
-- Замер (task-1-report.md, 2026-08-02): 100000 строк issues одного проекта,
-- 1000 (1%) старше условного порога хранения — та же малая доля кандидатов
-- на удаление, что и в проде (чистка тикает раз в час, срок хранения —
-- недели/месяцы). ДО индекса: Seq Scan on issues, cost=0.00..3179.00.
-- ПОСЛЕ: Index Scan using issues_last_seen_idx, cost=0.30..376.82.
--
-- ЛОВУШКА НЕДОСТРОЕННОГО ИНДЕКСА (раунд правок 1, task-1-report.md): если
-- построение CONCURRENTLY прервётся на боевом объёме (обрыв соединения,
-- нехватка памяти, ручная отмена), PostgreSQL не убирает недостроенный
-- индекс, а оставляет его в каталоге со статусом «недействителен». При
-- повторном накате этой же миграции IF NOT EXISTS увидит объект с таким
-- именем и МОЛЧА пропустит создание — не починит недействительный индекс.
-- Миграция отчитается об успехе, гейт схемы будет зелёным, а рабочего
-- индекса не будет: планировщик недействительные индексы не берёт.
--
-- Это относится ко всем шести индексам 0031-0036 одинаково — этот докблок
-- задаёт шаблон, повторять его в каждом файле не нужно.
--
-- Проверка после наката (документировано также в internal/docs/{ru,en}/upgrade.md):
--   SELECT indexrelid::regclass, indisvalid FROM pg_index WHERE NOT indisvalid;
-- Если в списке один из шести индексов — построение прервалось. Лечится:
--   DROP INDEX CONCURRENTLY <имя_индекса>;
-- и повторным накатом миграций — IF NOT EXISTS на этот раз не увидит объекта
-- с таким именем и построит индекс заново. НЕ убирайте IF NOT EXISTS из
-- миграций ради этой ловушки: без него повторный накат после частичного
-- успеха (другие таблицы уже проиндексированы) падал бы на них тоже.
CREATE INDEX CONCURRENTLY IF NOT EXISTS issues_last_seen_idx
    ON issues (last_seen);
