-- backward-compatible: yes (ADD COLUMN с дефолтом; старый бинарь на новой
-- схеме продолжает вставлять ключи без kind и получает legacy).
--
-- kind — тип DSN-ключа: чем этим ключом можно пользоваться. Знание «какому
-- типу какой сигнал приёма разрешён» живёт НЕ здесь, а константной матрицей
-- в internal/ingest (см. ADR 0012): БД хранит тип, приём решает допуск.
--
-- DEFAULT 'legacy' СОЗНАТЕЛЬНО ОСТАЁТСЯ и после раскатки. Соблазн снять его
-- («вставка, забывшая kind, не должна молча получать полный допуск») ломает
-- откат релиза: старый CreateKey вставляет (project_id, public_key) без kind,
-- и при NOT NULL без дефолта после отката перестают создаваться ключи, а
-- следом проекты. Fail-closed держится на стороне Go: пустой KeyKind матрица
-- приёма трактует как отказ по всем сигналам.
ALTER TABLE project_keys ADD COLUMN kind text NOT NULL DEFAULT 'legacy'
    CHECK (kind IN ('browser','server','agent','legacy'));
