-- Находка №46, вторая половина — та же надобность, что у 0054, но для
-- issues.culprit: поиск (issue/query.go, buildIssueFilter) проверяет ОБЕ
-- колонки одним условием (`title ILIKE $N OR culprit ILIKE $N`), поэтому без
-- индекса на culprit половина условия по-прежнему шла бы последовательным
-- сканом, даже с issues_title_trgm_idx (0054) на месте — OR по двум
-- непроиндексированной/проиндексированной колонке не даёт планировщику
-- избежать Seq Scan: ему всё равно нужно проверить culprit на каждой строке,
-- которую не отсеял индекс title.
--
-- Это не только логический вывод — проверено эмпирически (task-8-report.md):
-- с одним лишь title-индексом (0054 накачена, эта миграция ещё нет) план
-- ОСТАЁТСЯ Seq Scan, execution time не меняется (135.5 мс — то же, что и без
-- всякого trgm-индекса, 141.6 мс на count с учётом погрешности прогона);
-- BitmapOr появляется только после этой, второй миграции — см. докблок 0054
-- для дословного EXPLAIN до/между/после.
--
-- CONCURRENTLY, отдельный файл, ловушка недостроенного индекса — см. 0031 и
-- докблок 0054, тот же приём.
CREATE INDEX CONCURRENTLY IF NOT EXISTS issues_culprit_trgm_idx
    ON issues USING gin (culprit gin_trgm_ops);
