-- backward-compatible: yes (новый индекс)
--
-- Находка №45: PostgreSQL не создаёт индекс на ССЫЛАЮЩЕЙСЯ стороне внешнего
-- ключа автоматически (в отличие от стороны, на которую ссылаются, — там
-- индекс обязан существовать, иначе миграция ADD CONSTRAINT сама бы упала).
-- Значит проверка каскада при удалении родителя (ON DELETE CASCADE/SET NULL)
-- — это SELECT/DELETE по значению ссылающейся колонки, и без индекса он идёт
-- полным сканом дочерней таблицы. На issues (3 млн строк, ссылается на
-- projects/users) это означает: удаление аккаунта из интерфейса идёт
-- десятками секунд, страница отдаёт отказ по таймауту, а блокировка, которую
-- Postgres держит на время проверки, задевает запись новой проблемы на
-- горячем пути приёма (тот же issues, конкурентный INSERT).
--
-- Список ниже — НЕ аудиторский план (тот называл 8 колонок), а фактический
-- результат запроса к системному каталогу поднятой тестовой базы: все
-- ограничения внешнего ключа (pg_constraint.contype='f'), для которых нет
-- НЕ партиционного индекса, начинающегося с тех же колонок в том же
-- порядке, что и в ограничении. Партиционный индекс на постороннюю колонку
-- (например metric_incidents_one_open_idx, WHERE status='open') намеренно не
-- засчитан как покрытие: планировщик не может доказать, что удаляемая
-- строка родителя попадает под чужой предикат, и для строк вне условия
-- всё равно скана не избежать. Текст запроса — в task-2-report.md
-- (потребуется задаче 4 для сторожа на то же правило).
--
-- Список (16 ограничений, этот файл и 0038-0052 — по одному индексу на
-- каждое): alert_channels.project_id (этот файл), alert_throttle.rule_id,
-- check_queue.leased_by, issues.assignee_id, metric_incidents.rule_id,
-- monitor_channels.channel_id, notification_outbox.channel_id,
-- org_invites.org_id, org_members.user_id, project_keys.project_id,
-- project_teams.team_id, status_page_monitors.monitor_id,
-- status_pages.project_id, team_members.user_id, team_members(team_id,
-- org_id), team_members(org_id, user_id) — три отдельных ограничения на одну
-- таблицу team_members с разным ведущим столбцом требуют трёх разных
-- индексов, один не покрывает остальные.
--
-- Один индекс на файл, CONCURRENTLY, ловушка недействительного индекса после
-- обрыва построения — тот же вывод эксперимента и та же операционная
-- особенность, что и у 0031-0036 (см. докблок
-- 0031_issues_last_seen_idx.up.sql и task-1-report.md); не дублирую здесь.
--
-- Эта колонка (alert_channels.project_id) NOT NULL — индекс полный, без
-- условия.
CREATE INDEX CONCURRENTLY IF NOT EXISTS alert_channels_project_id_idx
    ON alert_channels (project_id);
