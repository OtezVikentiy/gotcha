-- backward-compatible: yes (ADD COLUMN nullable, без дефолта — старый бинарь,
-- не знающий об этой колонке, продолжает работать: она просто остаётся NULL).
--
-- W3-E (аудит 2026-08-27, кластер 4): у пяти источников инцидентов (host/
-- metric/slo/profile/trace) шаг 0 лесенки проходит через escalation.
-- SendStepIfDue, и провал LogStep там получает до maxLogFailureAttempts
-- (internal/escalation/step.go) попыток на СЛЕДУЮЩИХ тиках планировщика —
-- ретрай там ЕСТЕСТВЕННО совпадает с повторной отправкой того же шага
-- (это часть замысла лесенки, не баг). У uptime шаг 0 доставляет Detector
-- (свой B5 hold/grace/ретрай, минуя SendStepIfDue — см. миграцию 0084 и
-- Service.OpenUnacked), а повторная ОТПРАВКА "down" здесь недопустима:
-- Detector отправляет "down" РОВНО ОДИН раз при успехе, и ретрай LogStep не
-- должен превращаться в дубль пейджа. Значит ретраить нужно СТРОГО лог, не
-- уведомление — а для этого нужно ПОМНИТЬ, каким именно каналам "down" уже
-- реально ушёл, не полагаясь на ТЕКУЩИЙ (могущий уже смениться) список
-- каналов монитора/проекта.
--
-- notify_open_channels — тот самый снимок: ID каналов, в которые Detector.
-- notifyOpen реально поставил задачу для шага 0 этого инцидента (см.
-- Notifier.NotifyOpenStep0), записывается ОДИН раз сразу после доставки,
-- НЕЗАВИСИМО от исхода логирования. NULL — ретраить нечего: либо лог уже
-- завершён (успешно или принудительно после потолка попыток —
-- Detector.retryStepZeroLog очищает колонку в обоих случаях), либо
-- инцидент старше этой миграции. Отдельная колонка, не переиспользование
-- escalation_step_log_failures: та таблица — общий для 6 источников счётчик
-- попыток (source, incident, step) без данных о том, ЧТО именно ретраить —
-- канал-специфичное состояние остаётся доменным, как и notify_open_failed/
-- notify_open_attempts (0084).
ALTER TABLE incidents ADD COLUMN notify_open_channels bigint[];
