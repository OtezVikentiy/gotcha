-- меняет ни одну колонку существующей схемы; новая таблица — аддитивна).
--
-- W2-C, находка 3 аудита 2026-08-27 (кластер 1, DEDUP-P1.md): SendStepIfDue
-- логировал шаг (incident_escalations) и бампал escalation_level двумя
-- независимыми обращениями к БД (после первого прохода правки — уже не
-- тремя: LogStep пишется в цикле по каналам, bump — отдельно, но это те же
-- две границы) — смерть процесса между ними давала либо дубль пейджа
-- (уведомили и залогировали, не забампили — следующий тик шлёт ступень
-- заново), либо дыру в логе (забампили, не залогировали — ошибка
-- одиночного INSERT внутри цикла по каналам молча проглатывалась, bump шёл
-- дальше). Полноценная SQL-транзакция на LogStep+bump здесь НЕ заводится
-- (это решение по существу, не только ради скоупа): между ними стоит
-- notifyStep — постановка задачи во ВНЕШНИЙ outbox, эффект, который
-- транзакция БД откатить не может. Смерть процесса СРАЗУ ПОСЛЕ успешного
-- notifyStep, но до коммита гипотетической tx(log+bump), дала бы ровно тот
-- же дубль пейджа на следующем тике, что и в этом дизайне — транзакция
-- убрала бы только рассогласование МЕЖДУ двумя записями в БД между собой,
-- не убрала бы окно дубля-в-outbox. Идемпотентный LogStep (см. ниже) даёт
-- ту же гарантию (лог и уровень не расходятся) плюс настоящий констрейнт в
-- схеме, переживающий будущий рефакторинг вызывающего кода — см. также
-- internal/escalation/step.go, докблок SendStepIfDue.

-- Схлопнуть уже существующие дубли ДО создания UNIQUE-индекса — без этого
-- ALTER TABLE ниже падает на живых данных везде, где дубль уже успел
-- записаться (а находка 3 ровно про то, что мог). Детерминированно: на
-- каждую четвёрку (source, incident, channel, step) остаётся строка с
-- МИНИМАЛЬНЫМ id (первая по времени запись, sent_at которой ближе всего к
-- реальному моменту доставки), лишние копии удаляются. down НЕ воскрешает
-- удалённые здесь дубли — это принципиально невозможно (какая именно
-- строка была "лишней", после DELETE не восстановить), и это не потеря
-- данных с самостоятельной ценностью: две строки на одну и ту же четвёрку
-- по определению описывают одну и ту же отправку одного и того же шага
-- одному и тому же каналу, различаются только sent_at повторной попытки.
DELETE FROM incident_escalations dup
    USING incident_escalations keep
    WHERE dup.id > keep.id
      AND dup.incident_source = keep.incident_source
      AND dup.incident_id = keep.incident_id
      AND dup.channel_id = keep.channel_id
      AND dup.step = keep.step;

ALTER TABLE incident_escalations
    ADD CONSTRAINT incident_escalations_source_incident_channel_step_key
    UNIQUE (incident_source, incident_id, channel_id, step);

-- escalation_step_log_failures — граница попыток на "залогировать эту
-- ступень" (W2-C находка 3, условие 2 ревью): без неё устойчиво падающий
-- LogStep (побитые данные, отвалившийся constraint, недоступная PG) не даёт
-- bump'у ни разу пройти → следующий тик берёт ТУ ЖЕ ступень → notifyStep
-- пейджит СНОВА → LogStep падает СНОВА — бесконечный пейджинг-шторм на
-- каждом тике, хуже исходной дыры (та молчала, шторм будит дежурного
-- всю ночь). internal/escalation/step.go считает попытки здесь и после
-- maxLogFailureAttempts (см. её докблок) продвигает bump принудительно, с
-- громким логом — прогресс важнее бесконечного шторма, тот же принцип, что
-- уже применён к частичному провалу notifyStep (см. докблок SendStepIfDue).
-- Без FK на incident_id — тот же приём, что у incident_escalations самой:
-- источников 6, таблица одна, здесь PK — сама четвёрка, что и различает
-- попытки (source, incident, step), без channel_id — граница на ступень
-- целиком, не на канал.
CREATE TABLE escalation_step_log_failures (
    incident_source text NOT NULL,
    incident_id bigint NOT NULL,
    step int NOT NULL,
    attempts int NOT NULL DEFAULT 0,
    last_attempt_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (incident_source, incident_id, step)
);
