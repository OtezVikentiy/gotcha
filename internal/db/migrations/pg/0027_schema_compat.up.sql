-- backward-compatible: yes (новая таблица)
--
-- Признак обратной совместимости применённых миграций. Гейт схемы требовал
-- точного равенства версий: база впереди бинаря — отказ старта. Ветка осознанна
-- (защита от тихого даунгрейда), но её следствием был невозможный откат релиза:
-- выкатили, миграции применились, откатили бинарь — он не стартует, и вернуть
-- можно только из бэкапа.
--
-- Старый бинарь не может знать, аддитивны ли миграции, которых он не содержит:
-- признак, живущий в коде или в файлах, для отката бесполезен. Поэтому признак
-- едет вместе со схемой — сюда его пишет тот, кто применял миграции, а читает
-- любой бинарь, включая откатившийся назад.
--
-- Признаки обеих схем живут в PostgreSQL: без него процесс не стартует вообще,
-- и держать служебные метаданные в двух местах значит завести второй источник
-- истины об одном и том же.
CREATE TABLE schema_compat (
    target              text   NOT NULL CHECK (target IN ('pg', 'ch')),
    version             bigint NOT NULL,
    backward_compatible boolean NOT NULL,
    applied_at          timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (target, version)
);
