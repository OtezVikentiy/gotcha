-- backward-compatible: yes (новый skip-индекс)
-- Skip-индекс minmax на events.timestamp. Первичный ключ (ORDER BY project_id,
-- issue_id, timestamp) не отсекает по времени без ограничения на issue_id:
-- CountsSince (детектор всплесков) группирует по issue_id за окно времени, то
-- есть issue_id по построению не ограничен, и запрос читает всю
-- партицию-месяц. На проекте со 100М событий/месяц это ~1ГиБ чтения в минуту
-- при ~350К полезных строк — деградация пилообразная (первого числа дёшево,
-- к концу месяца дороже всего).
-- Про MATERIALIZE — см. 0015. Здесь сознательно НЕ материализуем: события
-- живут TTL 90 дней (0001), куски сменятся сами по мере ротации, и выигрыш
-- проявится постепенно, а не одномоментной тяжёлой мутацией по всей таблице
-- на старте. Если это неприемлемо для конкретного инстанса — материализовать
-- вручную: ALTER TABLE events MATERIALIZE INDEX idx_events_timestamp.
--
-- Замер (2026-08-02, testcontainers clickhouse/clickhouse-server:25.3-alpine):
-- 30 суток одного project_id, 750000 строк, кусков слито в один (OPTIMIZE
-- TABLE events FINAL — воспроизводит состояние ближе к концу месяца, когда
-- фоновые merge уже стёрли суточные границы кусков). Из 200 issue_id только
-- 20 "живут" весь месяц, остальные 180 перестают присылать события после
-- 5-х суток (реалистичное затухание issue в трекере, а не подгонка). Запрос —
-- дословный CountsSince, окно = последние 10 минут месяца, groups=20 в обоих
-- случаях (корректность не изменилась). read_rows ДО индекса = 605038, ПОСЛЕ
-- MATERIALIZE = 163092 — сокращение в ~3.7 раза при доле окна времени ~0.023%
-- от объёма месяца. Индекс берётся. (Разбор в задаче 3, подпроект «цена
-- запросов»: временный TestMeasureEventsTimestampIndexReadRows использован и
-- удалён после снятия числа.)
ALTER TABLE events ADD INDEX IF NOT EXISTS idx_events_timestamp timestamp TYPE minmax GRANULARITY 4;
