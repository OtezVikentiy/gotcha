package export

import (
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"

	"gitflic.ru/otezvikentiy/gotcha/internal/ingest"
)

// maskedValue — заменитель прямых идентификаторов пользователя в выгрузке.
// Одна константа на весь пакет: одинаковая маска в CSV-колонках и в JSON —
// признак, по которому получатель выгрузки узнаёт «данные скрыты», а не
// повод гадать, что означает конкретное значение.
const maskedValue = "[masked]"

// MaskUser прячет прямые идентификаторы пользователя — IP и email. Для
// user_id используется PseudonymizeUserID (см. ниже), не эта функция:
// раньше user_id вовсе не маскировался, а докблок объяснял это тем, что
// «user_id внутренний и нужен, чтобы посчитать, сколько пользователей
// задело» — это было неверно. SDK кладёт в user.id ровно то, что передал
// клиент (Sentry envelope user.id), и на практике это сплошь и рядом логин
// или email, а не суррогатный внутренний идентификатор, — то есть поле
// годами уезжало сырым именно из-за этого объяснения. Посчитать «сколько
// пользователей задело» можно по стабильному псевдониму
// (PseudonymizeUserID), не храня исходное значение в файле выгрузки.
//
// Пустая строка не превращается в маску: пустая колонка честнее ложного
// «данные скрыты» там, где данных не было — иначе по выгрузке нельзя было бы
// отличить «email скрыт» от «email не собирался вовсе» (важно, когда на
// приёме уже включён скрабинг и user_email в хранилище и так пуст).
func MaskUser(ip, email string) (string, string) {
	if ip != "" {
		ip = maskedValue
	}
	if email != "" {
		email = maskedValue
	}
	return ip, email
}

// userIDPseudonymHexLen — длина псевдонима user_id в hex-символах (8 байт
// HMAC-SHA256, усечённых). Полных 64 hex-символов SHA-256 для колонки CSV
// не нужно: псевдоним не хранится и не сверяется вручную, а нужен только
// для группировки строк одного пользователя внутри одной выгрузки — 8 байт
// с огромным запасом достаточно, чтобы не столкнуть два разных user_id
// в пределах одной заявки (счётные тысячи-десятки тысяч строк, не миллиарды).
const userIDPseudonymHexLen = 16

// PseudonymizeUserID заменяет user_id стабильным псевдонимом:
// HMAC-SHA256(salt, userID), усечённым до userIDPseudonymHexLen hex-символов.
// Псевдоним, а не статичная маска [masked] (как MaskUser для IP/email) —
// user_id используется, чтобы посчитать «сколько уникальных пользователей
// задело» (см. переписанный докблок MaskUser выше), и статичная маска убила
// бы эту возможность: все строки схлопнулись бы в одно значение.
//
// salt — одноразовый, генерируется NewExportSalt() ОДИН раз на заявку
// (internal/export/source_events.go: eventSource.Stream), не хранится и не
// переиспользуется между заявками. Это даёт ровно нужное свойство:
// одинаковый user_id → одинаковый псевдоним ВНУТРИ одной выгрузки (можно
// посчитать уникальных пользователей), а по значению нельзя ни восстановить
// исходный user_id (HMAC необратим без salt), ни сопоставить одного и того
// же пользователя МЕЖДУ разными выгрузками (salt в каждой свой) — лишняя
// корреляция между файлами, которую никто не просил и которая сама по себе
// была бы утечкой (получатель двух выгрузок мог бы сшить активность
// пользователя по псевдониму, если бы он был одинаков всегда).
//
// Пустая строка не превращается в псевдоним — тот же принцип, что и в
// MaskUser: пустая колонка честнее «псевдонима пустого значения».
func PseudonymizeUserID(userID string, salt []byte) string {
	if userID == "" {
		return ""
	}
	mac := hmac.New(sha256.New, salt)
	mac.Write([]byte(userID))
	sum := mac.Sum(nil)
	return hex.EncodeToString(sum)[:userIDPseudonymHexLen]
}

// NewExportSalt генерирует одноразовый salt для PseudonymizeUserID: 16
// случайных байт из crypto/rand, РОВНО НА ОДНУ заявку выгрузки — вызывается
// один раз за вызов eventSource.Stream (source_events.go: eventSource.Stream)
// и никогда не переживает его. НЕ на проект и НЕ на инстанс — сознательный
// выбор границы жизни salt, а не забытая оптимизация:
//
//   - salt на ПРОЕКТ (или тем более на инстанс целиком) дал бы одинаковый
//     псевдоним одного и того же user_id в ЛЮБЫХ двух выгрузках этого
//     проекта — то есть корреляцию активности пользователя МЕЖДУ файлами,
//     которую никто не заказывал и которая сама по себе была бы утечкой:
//     получатель двух выгрузок (например, в разное время двум разным людям)
//     мог бы сшить их по псевдониму пользователя, как если бы user_id не
//     маскировался вовсе;
//   - salt на Stream даёт ровно нужное и не более: «одинаковый user_id —
//     одинаковый псевдоним ВНУТРИ одной выгрузки» (можно посчитать
//     уникальных пользователей одного файла), но «разные выгрузки —
//     заведомо разные псевдонимы одного и того же человека» (сопоставить
//     файлы по user_id нельзя).
//
// Контрактная уборка 2026-08-28 (F1′ CONTRACT-DECISIONS.md): это поведение
// правильное и остаётся как есть, но раньше было названо только здесь, в
// докблоке кода, — получатель ФАЙЛА (не читающий internal/export/pii.go)
// мог тихо попытаться склеить две выгрузки по user_id и получить молча
// неверный результат. Теперь свойство явно и по-человечески названо
// РЯДОМ с файлом (не внутри его потока данных — см. докблок Meta, meta.go,
// почему): BuildMeta (meta.go) кладёт PseudonymUniquenessNote в
// Meta.PseudonymNote для любой заявки Kind=events с IncludePII=false, откуда
// её забирают meta=1-ответ скачивания, атрибут data-pseudonym-masked на
// странице «Выгрузки» и письмо о готовности (см. докблок Meta) — см. также
// документацию выгрузок обеих локалей (internal/docs/{ru,en}/exports.md,
// раздел «PII»).
func NewExportSalt() []byte {
	salt := make([]byte, 16)
	if _, err := rand.Read(salt); err != nil {
		// crypto/rand.Read не возвращает ошибку на исправной ОС (поверх
		// /dev/urandom или эквивалента) — паника здесь означает отказ
		// системного источника энтропии при старте выгрузки, а не молчаливую
		// деградацию псевдонима до предсказуемого значения.
		panic("export: crypto/rand недоступен: " + err.Error())
	}
	return salt
}

// PseudonymUniquenessNote — текст пометки F1′: почему псевдоним user_id
// одной выгрузки нельзя сопоставить с другой (см. развёрнутое обоснование в
// докблоке NewExportSalt выше). Экспортирована и вынесена в константу, а не
// собрана инлайн в meta.go, ровно по одной причине: получатель видит этот
// текст в машиночитаемых метаданных (Meta.PseudonymNote, meta.go) и в письме
// о готовности (mailPayload, notify.go) — двух местах, которым формулировка
// обязана совпадать дословно, поэтому она стабильна и меняется так же
// осознанно, как список колонок CSV (EventColumns/IssueColumns) — правка
// текста здесь это правка контракта метаданных, а не рефакторинг строки.
//
// На английском независимо от локали инстанса: BuildMeta (meta.go) кладёт
// это значение в Meta.PseudonymNote без прогона через i18n.T() — Meta
// целиком (ScopeIssueID/FilterCode/PseudonymNote) машиночитаемая и не
// локализуется нигде в продукте, в отличие от человекочитаемой СВОДКИ
// заявки на веб-странице и в письме (exports.summary.*/exports.mail.*,
// internal/web/exports.go, internal/i18n/locales). В письме о готовности
// (mailPayload, notify.go) эта константа добавляется НЕПЕРЕВЕДЁННОЙ строкой
// рядом с локализованным телом письма ровно по той же причине.
const PseudonymUniquenessNote = "user_id pseudonyms are unique to this export and are not comparable with other exports"

// jsonScrubber — один общий *ingest.Scrubber на весь пакет, а не новый на
// каждый вызов MaskJSON: денилист константен (ingest.DefaultDenyKeys), и
// eventSource.toRecord зовёт MaskJSON дважды на КАЖДОЕ событие выгрузки
// (request и contexts, source_events.go) — до 400 000 конструирований
// Scrubber на заявку с потолком в 200k строк, каждое заново компилирует
// нормализованный денилист.
//
// Безопасен для конкурентного использования: ScrubJSON (и весь путь
// walk/scrubValue под ней) читает поля Scrubber (ScrubIP/ScrubEmail/
// denyNorm/allowNorm), но ни разу их не пишет — единственные мутации полей
// во всём internal/ingest/scrub.go происходят в NewScrubber (конструктор,
// однократно, до публикации переменной) и в SetAllowKeys, которую MaskJSON
// не зовёт. Мутирует ScrubJSON только ЛОКАЛЬНУЮ декодированную копию JSON
// каждого вызова (v, распакованный из raw), а не сам Scrubber, — конкурентные
// вызовы не делят это состояние между собой.
//
// ScrubFreeText выставлен в true ПОСЛЕ конструктора (мутация происходит
// однократно, до публикации переменной, — см. абзац выше про безопасность
// конкурентного доступа): выгрузка «без ПДн» — свой, более строгий контур,
// не зависящий от GOTCHA_SCRUB_FREETEXT конкретного инстанса. Без этого
// email, попавший в свободный текст (message, локальные переменные фрейма
// в stacktrace, breadcrumbs) на инстансе, где вольный скраб при приёме
// выключен, доехал бы до выгрузки открытым текстом даже при includePII=false
// — MaskJSON/MaskMessage полагаются на ScrubText (internal/ingest/scrub.go),
// а тот no-op при ScrubFreeText=false.
var jsonScrubber = newJSONScrubber()

func newJSONScrubber() *ingest.Scrubber {
	s := ingest.NewScrubber(true, true, ingest.DefaultDenyKeys())
	s.ScrubFreeText = true
	return s
}

// MaskJSON проходит по объекту и маскирует значения ключей из денилиста приёма
// (Authorization, Cookie, X-Api-Key и прочее — internal/ingest.DefaultDenyKeys).
// Тот же денилист, что и на приёме: список не дублируется, поведение не
// расходится. Битый или пустой вход возвращается как есть — выгрузка не должна
// молча терять то, что не смогла разобрать.
func MaskJSON(raw string) string {
	return jsonScrubber.ScrubJSON(raw)
}

// MaskMessage прогоняет человеко-читаемое свободнотекстовое поле события
// (message, exception_value) через тот же скрабер, что и приём
// (Scrubber.ScrubMessage, internal/ingest/scrub.go): email в тексте (RA-L10,
// при ScrubFreeText — см. newJSONScrubber выше, для выгрузки он всегда
// включён) и query-токены во встроенных URL ("GET https://api/x?token=…",
// вычищаются безусловно). Второго денилиста/регэкспа для выгрузки заводить
// незачем — поведение обязано совпадать с приёмом дословно.
func MaskMessage(text string) string {
	return jsonScrubber.ScrubMessage(text)
}

// MaskTags возвращает КОПИЮ карты тегов события с денилист-ключами
// (Authorization/Cookie/token и т.п., включая email/IP пользователя —
// user.email/user_ip и их варианты, см. emailAttrKeysNorm/ipAttrKeysNorm в
// internal/ingest/scrub.go) замаскированными тем же jsonScrubber, что и
// request/contexts (MaskJSON выше). Раньше маска PII проверяла только
// UserIP/UserEmail и request/contexts — колонка tags её обходила целиком:
// при выключенном GOTCHA_SCRUB_EMAIL событие могло нести user.email тегом,
// и оператор без права на «выгрузить как есть» получал файл, где
// user_email=[masked], а рядом в tags тот же адрес открытым текстом.
//
// КОПИЯ обязательна: Scrubber.ScrubTags мутирует карту на месте, а входная
// map[string]string принадлежит вызывающему (event.Stored из общего кеша/
// повторного использования, а не одноразовый снимок) — маскирование под
// выгрузку не должно быть видно никому, кто продолжает читать те же теги
// после возврата из этой функции.
func MaskTags(tags map[string]string) map[string]string {
	if len(tags) == 0 {
		return tags
	}
	cp := make(map[string]string, len(tags))
	for k, v := range tags {
		cp[k] = v
	}
	jsonScrubber.ScrubTags(cp)
	return cp
}
