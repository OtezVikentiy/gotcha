// literalKeyRe находит вызовы перевода — i18n.T(<выражение-контекста>, "ключ"),
// i18n.Tf(...), i18n.Tn(...).
//
// Первый аргумент — любое выражение, а не только литеральный ctx: хендлеры
// сплошь и рядом пишут i18n.T(r.Context(), …), и более узкая регулярка (см.
// историю правки — раньше требовала ровно "ctx") проходила мимо 61 ключа —
// ровно тех, что показываются на путях отказа (error.internal, весь
// err.auth.*, err.org.*, письма приглашений).
//
// Известное ограничение: [^,]+? не пройдёт через запятую внутри вложенных
// скобок первого аргумента (например i18n.T(withLocale(ctx, loc), "ключ")).
// Сегодня в дереве таких вызовов нет — все зовут T/Tf/Tn с ctx или
// r.Context() без вложенных запятых, — поэтому регулярку не усложняем;
// если такой вызов появится, сканер молча его пропустит.
var literalKeyRe = regexp.MustCompile(`i18n\.(T|Tf|Tn)\(\s*[^,]+?\s*,\s*"([^"]+)"(\s*\+)?`)

// minKeysFound — сколько ключей сканер обязан находить.
//
// План закрытия находки №17 оценивал: 676 находил старый сканер с
// требованием литерального ctx, 61 ключ проходил мимо него (676+61=737).
// Фактический прогон на этом дереве даёт 672 и 734 — план оценивал числа на
// глаз, до фактического запуска; расхождение в 3 ключа воспроизводится
// стабильно что для узкой, что для широкой регулярки (см. task-2-report.md),
// то есть это не потеря в самом расширении, а дрейф оценки плана относительно
// реального дерева. Порог зафиксирован по фактически найденному значению.
// Число работает вторым храповиком: если сканер станет видеть меньше, это
// регрессия самого сканера, а не каталога, и её иначе не заметить — проверка
// «все найденные ключи есть в каталоге» при пустой находке зелёная сама по
// себе.
//
// collectI18nKeys не сканирует _templ.go (Generated) и _test.go — оба
// исключения проверены отдельно: число не изменилось (было и осталось 734),
// потому что единственный литеральный ключ в тестах ("a11y.chart.sparkline_empty"
// в internal/web/svg_labels_internal_test.go) уже встречается и в обычном
// коде, а _templ.go только дублирует свой .templ. Так и должно быть — иначе
// исключения этих файлов из обхода сами оказались бы регрессией сканера.
//
// 734→733 — задача C8 подпроекта единиц: timeRangeLabel (timerange.templ)
// раньше дописывал суффикс "UTC" отдельным вызовом i18n.T(ctx, "range.utc_note")
// в конец подписи диапазона; теперь зону на каждой границе пишет сама
// humanize.Time, внешний суффикс убран как задвоение ("UTC UTC"), а
// единственное использование ключа с ним. Ключ удалён и из каталогов (иначе
// повис бы неиспользуемым переводом) — настоящее уменьшение находок, а не
// регрессия сканера, тот же приём, каким снижают maxDebtFormatExemptions и
// подобные потолки/полы по мере починки долга.
//
// 733→732 — задача C9: единственный вызов i18n.T(ctx, "onboarding.platform.other")
// (два места в onboarding.templ, но ключ один — сканер считает множеством, не
// счётчиком) заменён на конкатенацию i18n.T(ctx, "platform."+p) в цикле по
// org.Platforms — тем же приёмом, каким уже собираются ключи "range."+preset и
// "org.quota.kind."+kind. Конкатенация не литеральный ключ и этим сканером не
// считается (см. literalKeyRe и её обработку m[3]=="+" в collectI18nKeys) —
// новую группу "platform." проверяет отдельно TestDynamicKeysResolve
// (i18n_dynamic_test.go), не этот тест. Ключ переименован в "platform.other" и
// остался в каталогах (используется через ту же конкатенацию), поэтому это не
// потеря перевода — только потеря ОДНОГО литерального вызова из подсчёта.
const minKeysFound = 732

// TestEveryKeyInCodeExistsInCatalog — ключ, которого нет ни в одном каталоге,
// не ловило НИЧТО: рендер-тесты шаблонов проверяют только те значения,
// которые сами и подставили, поэтому страница с сырыми ключами вместо
// заголовков колонок проходила весь набор — перевода нет, ошибки нет, на
// экране «issues.table.level».
//
// Каталог не плоский (см. tree.go): обычные сообщения живут в Catalogs,
// формы множественного числа — отдельно в Plurals. Поэтому правило различает
// вызовы по имени функции — T/Tf ищут ключ в Catalogs, Tn — в Plurals.
// Ключ, найденный «не там» (например, обычный ключ вызван через Tn), — это
// находка, а не совпадение: на странице такой вызов отдаст сырой ключ вместо
// текста, ровно как и полное отсутствие ключа.
func TestEveryKeyInCodeExistsInCatalog(t *testing.T) {
	tree := Load(t)

	messageKeys, pluralKeys := collectI18nKeys(t, tree)
	total := len(messageKeys) + len(pluralKeys)
	if total < minKeysFound {
		t.Fatalf("сканер нашёл %d ключей (%d обычных + %d плюральных), ожидалось не меньше %d — это регрессия самого сканера, а не каталога",
			total, len(messageKeys), len(pluralKeys), minKeysFound)
	}

	var missing []string
	for k := range messageKeys {
		if _, ok := tree.Catalogs["ru"][k]; !ok {
			missing = append(missing, fmt.Sprintf("%s (i18n.T/Tf, нет в messages)", k))
		}
	}
	for k := range pluralKeys {
		if _, ok := tree.Plurals["ru"][k]; !ok {
			missing = append(missing, fmt.Sprintf("%s (i18n.Tn, нет в plurals)", k))
		}
	}
	sort.Strings(missing)
	if len(missing) > 0 {
		// Парность ru/en каталогов проверяет отдельный тест
		// (internal/i18n/catalog_test.go: TestCatalogsHaveIdenticalKeys),
		// поэтому здесь достаточно сверяться с одной локалью.
		t.Errorf("ключи используются в коде, но отсутствуют в каталоге (%d):\n  %s",
			len(missing), strings.Join(missing, "\n  "))
	}
}

// collectI18nKeys обходит Go- и templ-исходники дерева и делит найденные
// ключи на обычные (i18n.T/Tf) и плюральные (i18n.Tn) по имени вызванной
// функции — смешивать их в одно множество нельзя, каталог сам их не путает.
func collectI18nKeys(t *testing.T, tree *Tree) (messageKeys, pluralKeys map[string]bool) {
	t.Helper()
	messageKeys = map[string]bool{}
	pluralKeys = map[string]bool{}

	scan := func(body string) {
		body = stripCommentsPerLine(body)
		for _, m := range literalKeyRe.FindAllStringSubmatch(body, -1) {
			// Конкатенация ("range." + ключ) — не литеральный ключ, а
			// префикс: множество его значений знает только вызывающий, и
			// закрепляют его отдельные тесты рядом с местом сборки.
			if strings.TrimSpace(m[3]) == "+" {
				continue
			}
			if m[1] == "Tn" {
				pluralKeys[m[2]] = true
			} else {
				messageKeys[m[2]] = true
			}
		}
	}
	for _, f := range tree.GoFiles {
		// Сгенерированные _templ.go — это скомпилированные .templ, их
		// вызовы i18n дублируют находки из .templ-исходника, который
		// сканируется отдельно ниже. Поле Generated для того и заведено
		// (см. tree.go) — без него сканер гонял бы вдвое больше текста
		// без единой новой находки.
		if f.Generated {
			continue
		}
		// Тест вправе намеренно звать несуществующий ключ, проверяя
		// поведение продукта при дыре в каталоге (T/Tn возвращают сам
		// ключ, если перевода нет — это и есть проверяемое поведение,
		// см. internal/web/dynamic_keys_test.go). Такой вызов — часть
		// проверки, а не находка; включение _test.go в обход роняло бы
		// сторож на первом же подобном тесте с заведомо неверным ключом.
		if strings.HasSuffix(f.Path, "_test.go") {
			continue
		}
		scan(f.Body)
	}
	for _, f := range tree.Templates {
		scan(f.Body)
	}
	return messageKeys, pluralKeys
}

// stripCommentsPerLine убирает строчные комментарии: в них встречаются
// примеры вызовов (в том числе в этом самом файле — в комментарии к
// literalKeyRe выше), и без вычищения сканер принимал бы их за настоящие
// ключи.
//
// Сама вычистка одной строки — stripTrailingComment из i18n_leak_test.go, а
// не второй разбор той же идеи здесь: там уже есть цикл, который ищет "//" не
// по первому вхождению, а по первому вхождению С ЧЁТНЫМ числом кавычек ПЕРЕД
// НИМ — иначе комментарий после URL-литерала на той же строке
// (`"https://..." // текст`) не отрезался бы: strings.Index нашёл бы "//"
// внутри самого URL и остановился бы на нём, не дойдя до настоящего
// комментария правее. Достаточно строчных комментариев: блочные в этом коде
// не используются для примеров, а полноценный разбор Go и templ ради теста —
// цена выше пользы.
func stripCommentsPerLine(src string) string {
	lines := strings.Split(src, "\n")
	for i, line := range lines {
		lines[i] = stripTrailingComment(line)
	}
	return strings.Join(lines, "\n")
}
