// TestNoUndefinedCSSClasses — класс, использованный в разметке без
// определения в app.css, не ломает ни сборку, ни тесты: блок просто
// рендерится без стилей и выглядит «пресно», а не сломанно — старый ручной
// список (internal/web/csscontract_test.go, удалён этой правкой) уже пропустил
// так минимум два класса (muted, btn-sm) свежей разметки, потому что список
// пополнялся вручную и адресно, а не полным перебором.
//
// Раунд правок 1: изначально правило смотрело только в Tree.Templates.
// Разметка, собранная строкой в .go (internal/web/svg.go, svgaxis.go —
// SVG-графики и flame-графы), — тоже разметка, и её вынесение "вне
// периметра" воспроизводило бы ровно тот дефект, ради которого затевался
// этот подпроект: сторож молча не проверяет часть того, что заявляет.
// Поэтому правило теперь обходит Tree.GoFiles ДОПОЛНИТЕЛЬНО к Tree.Templates.
//
// Сгенерированные (f.Generated) исключены — _templ.go дублирует свой
// .templ-исходник (то же решение, что и в i18n_keys_test.go). _test.go НЕ
// исключены, в отличие от i18n_keys_test.go: там исключение оправдано тем,
// что тесты намеренно зовут несуществующие i18n-ключи, проверяя поведение
// при дыре в каталоге, — качественно другая причина, которой здесь нет.
// Здесь литеральный class="..." в _test.go — это либо regexp-фикстура,
// сверяющая рендер с реальным классом разметки (internal/web/probes_test.go:22:
// `class="probe-token"` внутри regexp.MustCompile для проверки вывода), либо
// строка assert'а — в обоих случаях это тот же самый класс, что и в
// исходной разметке, и его стоит видеть: практическая проверка (см. round-1
// раздел task-5-report.md) — без исключения _test.go находится ровно
// probe-token, который и так уже был найден со стороны .templ, дублей-
// находок из-за этого не возникло.
func TestNoUndefinedCSSClasses(t *testing.T) {
	tree := Load(t)
	defined := cssDefinedClasses(tree.CSS.Body)

	exempt := ExemptedValues(permanentCSSClassExemptions)
	for v := range ExemptedValues(debtCSSClassExemptions) {
		exempt[v] = true
	}

	// seen — не "любой класс, встреченный в разметке", а именно множество
	// НЕОПРЕДЕЛЁННЫХ классов, найденных в этом прогоне. Так храповик
	// CheckExemptions работает правильно: если класс получит стиль в app.css
	// (находку починят), он выпадет из seen и исключение станет "устаревшим"
	// — CheckExemptions заставит убрать строку из списка, а не позволит ей
	// молча остаться прикрывать будущие такие же находки. Если бы seen
	// собирал вообще все встреченные в разметке классы (включая уже
	// определённые), почин записи стал бы неотличим от неё же нетронутой.
	seen := map[string]bool{}
	reported := map[string]bool{}

	handle := func(path string, line int, name string) {
		if defined[name] {
			return
		}
		seen[name] = true
		if exempt[name] || reported[name] {
			return
		}
		reported[name] = true
		t.Errorf("%s:%d: класс %q используется в разметке, но не определён в app.css", path, line, name)
	}

	for _, f := range tree.Templates {
		scanClassAttrs(f.Path, f.Body, handle)
	}
	for _, f := range tree.GoFiles {
		// _templ.go — сгенерированный дубликат уже просканированного .templ
		// (см. doc-комментарий выше); авторский .go честно сканируется, в том
		// числе _test.go — причина отличия от i18n_keys_test.go там же.
		if f.Generated {
			continue
		}
		scanClassAttrs(f.Path, f.Body, handle)
	}

	CheckExemptions(t, "TestNoUndefinedCSSClasses (по замыслу)", permanentCSSClassExemptions, maxPermanentCSSClassExemptions, seen)
	CheckExemptions(t, "TestNoUndefinedCSSClasses (долг подпроекта G)", debtCSSClassExemptions, maxDebtCSSClassExemptions, seen)
}
