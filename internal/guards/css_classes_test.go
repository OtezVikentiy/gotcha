// classAttrRe находит литеральные атрибуты class="..." — как в .templ-
// разметке, так и в .go-файлах, собирающих HTML/SVG строкой (internal/web/
// svg.go, svgaxis.go; расширено раундом правок 1, см. TestNoUndefinedCSSClasses
// ниже).
//
// Динамические классы templ — class={ expr } или class={ "a", cond && "b" } —
// собираются в Go-коде шаблона внутри фигурных скобок БЕЗ кавычек вокруг них,
// поэтому эта регулярка (требующая именно двойных кавычек) их не видит и не
// может увидеть в принципе — templ не кладёт Go-выражение внутрь атрибута в
// кавычках. Множество значений такого класса знает только вызывающий (см. по
// тому же принципу i18n_dynamic_test.go — там аналогичная дыра для
// i18n-ключей, собранных конкатенацией, закрыта отдельными тестами рядом с
// местом сборки, а не этим сканером).
//
// В .go-эмиттерах та же логика НЕ работает: raw-string-литералы Go (в
// обратных кавычках) можно склеивать оператором "+", и склейка при этом
// может лежать МЕЖДУ настоящими двойными кавычками атрибута. Пример из
// живого кода (internal/web/svg.go:778):
//
//	`class="`+perfLatencyLineClasses[0]+`"`
//
// Как ИСХОДНЫЙ ТЕКСТ (а не как разобранное Go-выражение) эта строка содержит
// подряд: класс="  →  `+perfLatencyLineClasses[0]+`  →  ". Регулярка
// classAttrRe (ей неизвестен Go-синтаксис, только текст) честно находит пару
// кавычек и отдаёт всё, что между ними, — включая обратные кавычки, скобки и
// "+" оператора конкатенации. Проверено на этом самом примере: без
// дополнительного фильтра результатом было бы "имя класса"
// "`+perfLatencyLineClasses[0]+`", чего, конечно, не существует.
//
// Ту же природу имеет "находка" из строки-комментария (internal/web/svg.go:413:
// `// (class="…" или stroke="#…")`) — комментарий ОБСУЖДАЕТ атрибут class,
// не является им, а нужная кавычка внутри comment-текста всё равно с точки
// зрения регулярки валидна.
//
// Оба случая отсекает не сама classAttrRe (усложнять её не нужно), а
// validClassTokenRe ниже — единая проверка на "это вообще похоже на CSS-имя",
// применяемая ко всем найденным токенам одинаково, что для .templ, что для
// .go.
var classAttrRe = regexp.MustCompile(`class="([^"]*)"`)

// validClassTokenRe — токен похож на настоящее имя CSS-класса: буквы, цифры,
// "_", "-", первый символ — буква (цифра в начале однозначно не имя класса
// в этом дереве, а дефис/подчёркивание в начале среди используемых классов
// не встречаются — упрощает проверку без потери точности).
//
// Отфильтровывает ровно то, что описано в комментарии у classAttrRe:
// "`+perfLatencyLineClasses[0]+`" (содержит обратные кавычки, скобки, "+") и
// "…" из строки-комментария (не ASCII-буква) — оба не проходят эту проверку
// и не попадают ни в найденные использования, ни тем более в исключения.
// Настоящие имена классов из .templ (все 336 найденных при первом прогоне
// задачи) проверены — ни одно не отсеивается: у всех первый символ — буква.
var validClassTokenRe = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_-]*$`)

// cssCommentRe вырезает комментарии CSS перед разбором селекторов. Без этого
// шага комментарий, УПОМИНАЮЩИЙ класс в прозе (в app.css таких больше десятка:
// «См. .team-member-add-form: на узком экране...», «.btn-danger-ghost —
// опасное действие...»), засчитался бы за настоящее определение — а он им не
// является, это просто ссылка человека на другое правило по имени.
var cssCommentRe = regexp.MustCompile(`(?s)/\*.*?\*/`)

// cssClassNameRe вытаскивает ПОЛНОЕ имя класса из позиции после точки в уже
// избавленном от комментариев CSS.
//
// Здесь и разбирается главная ловушка задания: наивная проверка «содержит ли
// app.css подстроку ".chip"» засчитала бы селектор ".chip-large" за
// определение ".chip" — подстрока входит в подстроку. Явной проверки границы
// СПРАВА от точки эта регулярка не делает и она ей не нужна: `[A-Za-z0-9_-]*`
// жадный и без каких-либо ограничений после себя в шаблоне, поэтому Go-движок
// регулярных выражений при разборе ".chip-large" заберёт имя ЦЕЛИКОМ —
// "chip-large", а не только "chip". Множество определённых имён в результате
// содержит "chip-large" и НЕ содержит "chip" по отдельности; сравнение потом
// идёт точным членством в множестве (classDefined[name]), а не подстрокой —
// поэтому класс "chip" из разметки корректно не находит себе определения,
// даже если ".chip-large" в CSS есть. Отдельная постфактум-проверка границы
// (то, что обычно делают через `\b`) была бы и не нужна, и опасна: у Go `\b`
// считает словообразующими [0-9A-Za-z_], а дефис — нет, так что `\b` сработал
// бы ровно на границе "p"(словообразующий символ)/"-"(не словообразующий) —
// то есть решил бы, что ".chip" в ".chip-large" уже закончился, хотя на самом
// деле имя класса продолжается. Жадный разбор всего идентификатора СРАЗУ, а
// не пословный поиск с последующей проверкой \b, снимает эту ловушку в
// принципе.
//
// Первый символ имени не может быть цифрой — этим же ограничением попутно
// отсекаются десятичные дроби вида ".5s" / "rgba(20, 30, 50, .14)" (после
// точки там всегда цифра): отдельная проверка для чисел не нужна, они просто
// не начинают совпадение.
var cssClassNameRe = regexp.MustCompile(`\.([A-Za-z_-][A-Za-z0-9_-]*)`)

// cssDefinedClasses возвращает множество имён классов, у которых в app.css
// есть хотя бы один селектор вида .имя (после точки, комментарии вычищены).
func cssDefinedClasses(css string) map[string]bool {
	css = cssCommentRe.ReplaceAllString(css, "")
	out := map[string]bool{}
	for _, m := range cssClassNameRe.FindAllStringSubmatch(css, -1) {
		out[m[1]] = true
	}
	return out
}

// scanClassAttrs проходит файл построчно и для каждого литерального
// class="..." отдаёт report путь, номер строки (с единицы) и имя класса —
// но только токены, прошедшие validClassTokenRe. Общий код для .templ- и
// .go-источников: правило одно и то же, файл — просто текст, различий в
// разборе после этой точки нет.
//
// //-комментарии вычищаются ДО разбора — раунд правок 2 нашёл это на самом
// себе: doc-комментарии этого же файла дословно цитируют разметку в виде
// примеров (`class="empty"`, `class="probe-token"` — см. debtCSSClassExemptions
// и TestNoUndefinedCSSClasses ниже), а этот файл — обычный _test.go в дереве
// и попадает в Tree.GoFiles наравне со всеми. Без вычищения комментариев
// правило подмешивало бы себе находки из собственного текста: "empty" и
// "probe-token" встречались бы ещё и по пути internal/guards/css_classes_test.go,
// и тогда, даже если находку в app.css когда-нибудь починят, имя всё равно
// продолжало бы "встречаться" вечно — устаревшее исключение никогда не
// стало бы устаревшим, храповик CheckExemptions молчал бы там, где обязан
// потребовать вычистить строку.
//
// Приём и хелпер (stripTrailingComment) переиспользованы из i18n_leak_test.go
// как есть, а не написаны заново: там уже решена соседняя ловушка — "//"
// внутри строкового литерала (URL вида "https://") не должен считаться
// началом комментария, и проверяется это чётностью числа кавычек ПЕРЕД
// вхождением "//". Полностью закомментированная строка (doc-комментарий,
// trimmed начинается с "//") пропускается целиком — разбирать в ней нечего,
// это тот же приём, что в TestNoCyrillicUserFacingLiterals.
func scanClassAttrs(path, body string, report func(path string, line int, name string)) {
	for i, line := range strings.Split(body, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "//") {
			continue
		}
		checked := stripTrailingComment(line)
		for _, m := range classAttrRe.FindAllStringSubmatch(checked, -1) {
			for _, name := range strings.Fields(m[1]) {
				if !validClassTokenRe.MatchString(name) {
					continue
				}
				report(path, i+1, name)
			}
		}
	}
}

