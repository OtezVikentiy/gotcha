package guards

import (
	"regexp"
	"strings"
)

// Exemption — одна допущенная запись из множества, которое сторож
// перебирает: конкретное найденное нарушение вместе с обоснованием, почему
// оно временно разрешено, и ссылкой на находку (номер в аудите, тикет и
// т.п.), под которой оно заведено.
type Exemption struct {
	Value   string
	Why     string
	Finding string
}

// testingT — то немногое, что нужно CheckExemptions от приёмника. Узкий
// интерфейс вместо *testing.T нужен, чтобы механизм храповика можно было
// проверить самим тестом (см. tree_test.go, fakeT): без подмены пришлось бы
// просто верить, что CheckExemptions ругается в нужных случаях.
type testingT interface {
	Helper()
	Errorf(format string, args ...any)
}

// ExemptedValues возвращает множество значений из списка исключений — им
// удобно пользоваться как второй проход при переборе найденного: то, что
// сторож нашёл и что не входит в этот набор, — новое нарушение.
func ExemptedValues(list []Exemption) map[string]bool {
	out := make(map[string]bool, len(list))
	for _, e := range list {
		out[e.Value] = true
	}
	return out
}

// CheckExemptions проверяет сам список исключений, а не то, что он
// разрешает. Три вида нарушений:
//
//   - запись без причины (Why) — исключение без обоснования неотличимо от
//     молчаливого отключения проверки;
//   - список длиннее max — потолок растёт осознанно правкой числа, а не
//     сам по себе;
//   - запись на значение, которого больше нет в seen (устаревшее исключение)
//     — это главный случай: без него список только растёт, ведь ничто не
//     заставляет удалить строку, когда исходное нарушение уже исправлено, и
//     она продолжает прикрывать будущие такие же находки.
func CheckExemptions(t testingT, name string, list []Exemption, max int, seen map[string]bool) {
	t.Helper()

	for _, e := range list {
		if e.Why == "" {
			t.Errorf("%s: исключение %q (%s) без причины — заполните Why", name, e.Value, e.Finding)
		}
		if !seen[e.Value] {
			t.Errorf("%s: исключение %q (%s) устарело — нарушение больше не найдено, строку надо удалить из списка исключений",
				name, e.Value, e.Finding)
		}
	}
	if len(list) > max {
		t.Errorf("%s: список исключений разросся до %d записей при потолке %d — почините находки или осознанно поднимите потолок",
			name, len(list), max)
	}
}

// funcDeclRe распознаёт НАЗВАННОЕ объявление функции/блока в начале строки:
// Go "func" (с ресивером метода или без) либо templ-блок "templ" — оба
// начинают своё тело со строки, начинающейся с ключевого слова. Используется
// только чтобы ответить на вопрос «внутри какой функции лежит эта строка»,
// тем же текстовым способом без парсера, каким работает весь пакет (см.
// докблок tree.go, пункт 1) — вложенные func-литералы/замыкания не
// понимаются: находка внутри такого литерала относится к ближайшему
// НАЗВАННОМУ объявлению вокруг него, а не к отдельной внутренней области
// видимости. Каждому текущему вызывающему нужно только «в какой названной
// функции искать глазами», и это ровно то, что возвращается ниже.
//
// Регэксп, а не go/ast, — сознательный выбор, а не унаследованная привычка
// пакета: соседняя задача этой же волны в этом же internal/guards ушла
// именно на AST для СВОЕЙ проверки. Здесь регэксп остаётся, потому что его
// заявленная точность проверена эмпирически, а не предположена — ревью
// волны 3 прогнало отдельный go/ast-скрипт по всему дереву и сверило его с
// funcDeclRe: ложных срабатываний ноль (замыкания и `var x = func()` не
// матчатся, потому что не начинаются с нулевой колонки), пропуски нашлись
// только на generics (см. ниже) и уже закрыты.
//
// Опциональный `(?:\[[^\]]*\])?` после имени функции — список типовых
// параметров дженерика (func Foo[T any](...)). Без него ревью волны 3
// (задача W3-J) нашло скриптом на go/ast пять пропущенных объявлений
// (internal/chbatch/isolate.go:27, internal/host/resolve.go:83,102,
// internal/ingest/otlp.go:1436, internal/web/gapfill.go:16): "[T any]" рвал
// `(\w+)\s*\(` сразу после имени, и строки внутри такой функции молча
// приписывались ПРЕДЫДУЩЕЙ именованной функции выше по файлу — тот же класс
// тихой порчи контекста, который вся эта схема закрывает для номеров строк.
// На ресивере метода (`func (h Set[T]) ...`) такого списка в этом дереве
// сейчас нет ни разу — проверено тем же go/ast-скриптом — поэтому символ
// после ресивера им не расширен: расширять узор под случай, которого нет,
// значило бы гадать вместо проверки, а не задел на будущее.
var funcDeclRe = regexp.MustCompile(`^(?:func|templ)\s+(?:\(\s*\S+\s+\*?(\w+)\s*\)\s+)?(\w+)(?:\[[^\]]*\])?\s*\(`)

// funcContexts проходит body сверху вниз и возвращает для каждой строки (та
// же индексация, что у strings.Split(body, "\n")) имя ближайшего
// предшествующего объявления, найденного funcDeclRe — "" для строк выше
// первого объявления. Тип ресивера метода вплетается в имя как
// "Тип.Метод", чтобы два метода с одинаковым именем на разных ресиверах не
// схлопнулись в одно имя (почему это важно — см. докблок ContentAnchor).
func funcContexts(body string) []string {
	lines := strings.Split(body, "\n")
	ctx := make([]string, len(lines))
	current := ""
	for i, line := range lines {
		if m := funcDeclRe.FindStringSubmatch(line); m != nil {
			if m[1] != "" {
				current = m[1] + "." + m[2]
			} else {
				current = m[2]
			}
		}
		ctx[i] = current
	}
	return ctx
}

// ContentAnchor строит адресуемый по содержимому ключ исключения — замену
// прежней схемы "путь:строка" (exemptLoc, удалена этой правкой, волна 3
// аудита 2026-08-27, задача W3-J). Класс дыры, который эта схема чинит:
// любая правка ВЫШЕ найденной строки сдвигала все находки ниже неё по
// файлу, ключи "устаревали" молча, и сторож краснел от чужой безобидной
// правки — притом что ни одна находка на самом деле не менялась. Класс
// подтверждён за один день аудита четыре раза, включая случай, когда номера
// пересчитывались трижды в пределах одной задачи.
//
// Ключ — это путь к файлу, имя ближайшей объемлющей названной функции/
// templ-блока (funcContexts) и точная строка исходника, на которой стоит
// находка (без хвостового комментария, без крайних пробелов — тот же текст,
// с которым сверяется сам сканер, поэтому его можно скопировать из исходника
// буквально).
//
// Что это гарантирует: якорь не зависит НИ ОТ ОДНОЙ правки ВЫШЕ находки —
// номер строки вообще не входит в ключ — и не зависит от переразметки
// пробелов в другом месте файла. Он же различает повторяющиеся куски кода в
// одном файле, если ЛИБО они лежат в разных названных функциях, ЛИБО их
// полная строка исходника отличается каким-то другим токеном даже при
// одинаковом интересующем фрагменте — например, в
// internal/event/query_test.go два вызова `t1.Format(time.RFC3339)` стоят в
// одной и той же тестовой функции, но различимы, потому что на одной строке
// раньше стоит issue1, а на другой — issue2.
//
// Чего это НЕ гарантирует: две РАЗНЫЕ строки в ОДНОЙ функции, побайтово
// совпадающие после вычистки комментария и обрезки пробелов, всё равно
// схлопнутся — по одному тексту их не различить. Это жёсткий провал теста
// (см. recordAnchor), а не молчаливый выбор одной из двух. Схема также не
// переживает переименование объемлющей функции или правку САМОЙ строки
// находки — оба случая меняют якорь, и исключение придётся поправить руками,
// как и раньше; отличие от старой схемы в том, что это происходит только
// при настоящей правке находки, а не от постороннней вставки выше.
func ContentAnchor(path, funcName, line string) string {
	if funcName == "" {
		// Латиницей намеренно: этот файл (exempt.go, не _test.go) сам входит
		// в обход TestNoCyrillicUserFacingLiterals (i18n_leak_test.go) — там
		// нет исключения для internal/guards/, в отличие от
		// TestNoRawTimeFormattingOutsideHumanize. Кириллический литерал здесь
		// завёл бы находку в i18n-сторожа ради строки, которую никогда не
		// увидит посетитель сайта.
		funcName = "(top level)"
	}
	return path + " in " + funcName + ": " + line
}

// recordAnchor — вторая половина контракта ContentAnchor: якорь, совпавший
// с двумя РАЗНЫМИ строками исходника, неоднозначен и обязан провалить тест
// сразу, а не молча оставить ту строку, что была записана первой (это и
// есть класс дыры, ради закрытия которого затевалась вся эта правка — см.
// докблок ContentAnchor). seenLines хранит "якорь → строка, на которой он
// впервые встретился", в пределах одного прохода сканера.
//
// Повторная запись ТОГО ЖЕ якоря на ТОЙ ЖЕ строке — ожидаемый случай, не
// ошибка: два совпадения на одной физической строке исходника (в
// internal/web/svg.go есть строка с двумя вызовами `.Format("02.01")` подряд)
// — это одно место находки по замыслу, см. докблок над debtFormatExemptions
// в format_test.go (тот же приём, каким жила прежняя exemptLoc: ключ считает
// по строке, а не по вызову).
func recordAnchor(t testingT, name string, seenLines map[string]int, anchor string, line int) {
	t.Helper()
	if prev, ok := seenLines[anchor]; ok {
		if prev != line {
			t.Errorf("%s: якорь %q неоднозначен — совпадает и со строкой %d, и со строкой %d одновременно; нужен более точный контекст (другое имя функции или различающийся фрагмент строки), а не молчаливый выбор одной из них",
				name, anchor, prev, line)
		}
		return
	}
	seenLines[anchor] = line
}
