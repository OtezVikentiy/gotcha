//
// Получатель должен быть буквально «t» (а не любой идентификатор, кончающийся
// на «t», — иначе строка "fmt.Errorf(...)" совпала бы: «fmt» тоже оканчивается
// на «t»). Проверено по всему дереву (не только _test.go): единственные
